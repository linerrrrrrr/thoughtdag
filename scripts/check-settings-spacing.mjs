import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import ts from 'typescript';
import { checkSpacingSources } from './check-spacing-sources.mjs';

const project = fileURLToPath(new URL('../', import.meta.url));
const table = 'src/design-system/settings-spacing.json';
const runtimeCss = 'src/design-system/settings-spacing.css';
const sourceManifest = 'vendor/design-references/manifest.json';
const roleOrder = ['hint', 'heading', 'row', 'section'];
const token = role => '--settings-space-' + role;
const read = (root, file) => fs.readFileSync(path.join(root, file), 'utf8');
const readJson = (root, file) => JSON.parse(read(root, file));

function styleSheet(roles) {
  const lines = Object.entries(roles).map(([role, rule]) => '  ' + token(role) + ': ' + rule.px + 'px;');
  return ['/* Generated by npm run spacing:sync from settings-spacing.json. */',
    '.workspace-settings {', ...lines, '}', ''].join('\n');
}

function checkRules(registry, sources, report) {
  const usedPrinciples = new Set();
  for (const [id, principle] of Object.entries(registry.principles)) {
    if (!sources[principle.source]?.sections?.includes(principle.section) || !principle.guidance || !principle.adaptation) {
      report(table + ': incomplete upstream reference or adaptation for ' + id);
    }
  }
  for (const [role, rule] of Object.entries(registry.roles)) {
    if (!/^[a-z][a-z-]*$/.test(role) || !Number.isFinite(rule.px) || rule.px <= 0 ||
        !rule.use || !Array.isArray(rule.principles) || !rule.principles.length) {
      report(table + ': invalid spacing role ' + role);
      continue;
    }
    for (const id of rule.principles) {
      if (!Object.hasOwn(registry.principles, id)) report(table + ': unknown principle ' + id + ' for ' + role);
      usedPrinciples.add(id);
    }
  }
  for (const id of Object.keys(registry.principles)) {
    if (!usedPrinciples.has(id)) report(table + ': unused principle ' + id);
  }
  const values = roleOrder.map(role => registry.roles[role]?.px);
  if (!values.every((px, i) => Number.isFinite(px) && (!i || px > values[i - 1]))) {
    report(table + ': expected hint < heading < row < section');
  }
}

function checkPages(root, pages, report) {
  const file = 'src/lib/ui-store.ts';
  const source = ts.createSourceFile(file, read(root, file), ts.ScriptTarget.Latest, false);
  const section = source.statements.find(node => ts.isTypeAliasDeclaration(node) && node.name.text === 'SettingsSection');
  if (!section || !ts.isUnionTypeNode(section.type)) {
    report(file + ': cannot inventory SettingsSection for spacing registration');
    return;
  }
  const ids = new Set();
  for (const node of section.type.types) {
    if (!ts.isLiteralTypeNode(node) || !ts.isStringLiteral(node.literal)) {
      report(file + ': SettingsSection contains a non-literal section');
      continue;
    }
    ids.add(node.literal.text);
    if (!pages[node.literal.text]) report(table + ': unregistered settings page ' + node.literal.text);
  }
  for (const id of Object.keys(pages)) {
    if (!ids.has(id)) report(table + ': unknown settings page ' + id);
  }
}

function checkBindings(root, registry, report) {
  const registrations = new Map();
  const seen = new Set();
  const usedRoles = new Set();
  const coveredPages = new Set();
  const key = (file, selector, property) => [file, selector, property].join(' | ');
  for (const binding of registry.bindings) {
    const {file, selector, property, role, pages} = binding;
    if (!Object.hasOwn(registry.roles, role)) report(table + ': unknown role ' + role + ' for ' + selector);
    usedRoles.add(role);
    for (const id of pages) {
      if (!Object.hasOwn(registry.pages, id)) report(table + ': unknown binding page ' + id);
      coveredPages.add(id);
    }
    const wanted = 'var(' + token(role) + ')';
    const id = key(file, selector, property);
    if (registrations.has(id)) report(table + ': duplicate binding ' + id);
    registrations.set(id, binding.half ? 'calc(' + wanted + ' / 2)' : wanted);
  }
  for (const id of Object.keys(registry.pages)) {
    if (!coveredPages.has(id)) report(table + ': no spacing binding for page ' + id);
  }
  for (const id of Object.keys(registry.roles)) {
    if (!usedRoles.has(id)) report(table + ': no spacing binding for role ' + id);
  }
  const owners = new Set(registry.bindings.map(binding => binding.file));
  for (const entry of fs.readdirSync(path.join(root, 'src'), {recursive: true})) {
    if (!entry.endsWith('.css')) continue;
    const file = 'src/' + entry.split(path.sep).join('/');
    if (file === runtimeCss) continue;
    const content = read(root, file);
    if (!owners.has(file) && !content.includes('--settings-space-')) continue;
    postcss.parse(content, {from: file}).walkDecls(decl => {
      const where = file + ':' + decl.source.start.line;
      if (decl.prop.startsWith('--settings-space-')) report(where + ': spacing values belong in ' + table);
      for (const selector of decl.parent.selectors ?? []) {
        const id = key(file, selector, decl.prop);
        if (!registrations.has(id)) {
          if (decl.value.includes('--settings-space-')) report(where + ': unregistered spacing binding ' + id);
          continue;
        }
        seen.add(id);
        if (decl.value !== registrations.get(id)) report(where + ': ' + id + ' must use ' + registrations.get(id));
      }
    });
  }
  for (const id of registrations.keys()) {
    if (!seen.has(id)) report('Missing registered CSS declaration: ' + id);
  }
}

export function checkSettingsSpacing(root = project, {write = false} = {}) {
  const errors = [];
  const report = message => errors.push(message);
  try {
    const registry = readJson(root, table);
    const sources = readJson(root, sourceManifest).sources;
    errors.push(...checkSpacingSources(root));
    checkRules(registry, sources, report);
    checkPages(root, registry.pages, report);
    checkBindings(root, registry, report);
    const owner = 'src/components/ui/WorkspaceSettings.tsx';
    if (!/^import\s+['"]\.\.\/\.\.\/design-system\/settings-spacing\.css['"]/m.test(read(root, owner))) {
      report(owner + ': import the registered settings spacing stylesheet');
    }
    const expected = styleSheet(registry.roles);
    if (write && !errors.length) fs.writeFileSync(path.join(root, runtimeCss), expected);
    else if (read(root, runtimeCss).replace(/\r\n/g, '\n') !== expected) {
      report(runtimeCss + ': generated values differ from the table; run npm run spacing:sync');
    }
  } catch (error) {
    report('Settings spacing: ' + error.message);
  }
  return errors;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const errors = checkSettingsSpacing(project, {write: process.argv.includes('--write')});
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exitCode = 1;
  } else console.log('PASS settings spacing roles, page registrations, runtime CSS and source snapshots');
}
